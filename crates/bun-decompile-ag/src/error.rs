//! Typed errors for every structural problem the extractor can hit.
//!
//! Port of `src/lib/errors.ts`. The TS class hierarchy (subclasses of
//! `InvalidExecutableError`) flattens into one enum; user-facing messages are
//! kept identical — including the corruption hint the TS base class appends —
//! so CLI output matches the TS implementation during parity testing.

use thiserror::Error;

/// Appended to the message of every error that belonged to the TS
/// `InvalidExecutableError` hierarchy.
const CORRUPTION_HINT: &str = ". Either the binary is corrupted or it's not an executable file generated by `bun build --compile`.";

/// Result alias used throughout the crate.
pub type Result<T> = core::result::Result<T, ExtractError>;

/// Any structural problem found while parsing a compiled executable.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
#[non_exhaustive]
pub enum ExtractError {
    /// A structural invariant failed (TS `InvalidExecutableError`).
    #[error("{0}{CORRUPTION_HINT}")]
    InvalidExecutable(String),

    /// No Bun payload was found where one was expected (TS
    /// `InvalidTrailerError`).
    #[error("Invalid executable trailer ({0}){CORRUPTION_HINT}")]
    InvalidTrailer(String),

    /// An appended payload's trailing total byte count does not match the
    /// file size (TS `TotalByteCountMismatchError`).
    #[error("Executable byte count mismatch{CORRUPTION_HINT}")]
    TotalByteCountMismatch,

    /// No embedded Bun version string could be found and parsed (TS
    /// `VersionNotFoundError`).
    #[error("Version not found in executable{CORRUPTION_HINT}")]
    VersionNotFound,

    /// Neither a 32- nor a 24-byte Offsets struct probed as valid at the end
    /// of the payload. The TS implementation threw a bare `Error` here, so
    /// there is no corruption hint on this one.
    #[error("Could not parse Offsets struct: no valid struct size found")]
    OffsetsNotFound,

    /// A bundled file path did not begin with any known bunfs root. Also a
    /// bare `Error` in TS; message kept identical.
    #[error("Path does not start with Bun-fs root: {0}")]
    InvalidBunfsPath(String),

    /// A read ran past the end of the input. The TS equivalent was an
    /// uncaught `RangeError` out of `DataView`; here it is structured. The
    /// corruption hint applies: it means a length field pointed outside the
    /// file.
    #[error("Read of {len} byte(s) at offset {offset} is out of bounds{CORRUPTION_HINT}")]
    Truncated {
        /// Byte offset the read started at.
        offset: usize,
        /// Number of bytes the read wanted.
        len: usize,
    },
}

#[cfg(test)]
mod tests {
    use super::*;

    const HINT: &str = ". Either the binary is corrupted or it's not an executable file generated by `bun build --compile`.";

    #[test]
    fn display_invalid_executable_appends_corruption_hint() {
        let err = ExtractError::InvalidExecutable("Executable contains no bundled modules".into());
        assert_eq!(
            err.to_string(),
            format!("Executable contains no bundled modules{HINT}"),
        );
    }

    #[test]
    fn display_invalid_trailer_includes_detail_and_hint() {
        let err =
            ExtractError::InvalidTrailer("macho .bun section is missing the Bun trailer".into());
        assert_eq!(
            err.to_string(),
            format!(
                "Invalid executable trailer (macho .bun section is missing the Bun trailer){HINT}"
            ),
        );
    }

    #[test]
    fn display_total_byte_count_mismatch_matches_ts_text() {
        assert_eq!(
            ExtractError::TotalByteCountMismatch.to_string(),
            format!("Executable byte count mismatch{HINT}"),
        );
    }

    #[test]
    fn display_version_not_found_matches_ts_text() {
        assert_eq!(
            ExtractError::VersionNotFound.to_string(),
            format!("Version not found in executable{HINT}"),
        );
    }

    #[test]
    fn display_offsets_not_found_has_no_hint() {
        // The TS equivalent was a bare Error, not an InvalidExecutableError.
        assert_eq!(
            ExtractError::OffsetsNotFound.to_string(),
            "Could not parse Offsets struct: no valid struct size found",
        );
    }

    #[test]
    fn display_invalid_bunfs_path_has_no_hint() {
        assert_eq!(
            ExtractError::InvalidBunfsPath("/nope/index.js".into()).to_string(),
            "Path does not start with Bun-fs root: /nope/index.js",
        );
    }

    #[test]
    fn display_truncated_names_offset_and_length() {
        let err = ExtractError::Truncated { offset: 12, len: 4 };
        assert_eq!(
            err.to_string(),
            format!("Read of 4 byte(s) at offset 12 is out of bounds{HINT}"),
        );
    }
}
